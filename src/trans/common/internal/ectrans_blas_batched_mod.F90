MODULE ECTRANS_BLAS_BATCHED_MOD

USE EC_PARKIND, ONLY : JPRD, JPRM, JPIM
USE, INTRINSIC :: ISO_C_BINDING, ONLY : C_INT, C_DOUBLE, C_FLOAT, C_PTR, C_F_POINTER

IMPLICIT NONE

PRIVATE

PUBLIC :: GEMM_BATCHED

#ifdef HAVE_BATCHED_BLAS
! CBLAS constants
INTEGER(KIND=C_INT), PARAMETER :: CBLAS_COLMAJOR = 102
INTEGER(KIND=C_INT), PARAMETER :: CBLAS_NOTRANS  = 111
INTEGER(KIND=C_INT), PARAMETER :: CBLAS_TRANS    = 112

INTERFACE
  SUBROUTINE CBLAS_DGEMM_BATCH(LAYOUT, TRANSA, TRANSB, M, N, K, ALPHA, &
