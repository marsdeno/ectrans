      BIND(C, NAME='cblas_sgemm_batch')
    USE ISO_C_BINDING
    INTEGER(C_INT), VALUE :: LAYOUT
    INTEGER(C_INT), INTENT(IN) :: TRANSA(*), TRANSB(*)
    INTEGER(C_INT), INTENT(IN) :: M(*), N(*), K(*)
