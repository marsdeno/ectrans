    TYPE(C_PTR), INTENT(IN) :: A(*)
    INTEGER(C_INT), INTENT(IN) :: LDA(*)
    TYPE(C_PTR), INTENT(IN) :: B(*)
    INTEGER(C_INT), INTENT(IN) :: LDB(*)
    TYPE(C_PTR), INTENT(IN) :: C(*)
    INTEGER(C_INT), INTENT(IN) :: LDC(*)
