                             LDA(PERM(J)), LDB(PERM(J)), LDC(PERM(J)))) EXIT
      PERM(J+1) = PERM(J)
      J = J - 1
    ENDDO
    PERM(J+1) = II
  ENDDO

  ! Apply permutation to pointer arrays
  DO I = 1, BATCH_COUNT
    A_PERM(I) = A_PTRS(PERM(I))
    B_PERM(I) = B_PTRS(PERM(I))
    C_PERM(I) = C_PTRS(PERM(I))
  ENDDO

  ! Scan sorted triplets, build per-group shape arrays
  GROUP_COUNT = 0
  DO I = 1, BATCH_COUNT
    II = PERM(I)
    IF (I == 1) THEN
      SAME = .FALSE.
    ELSE
      J = PERM(I-1)
      SAME = (M(II)   == M(J)   .AND. N(II)   == N(J)   .AND. K(II)   == K(J)   .AND. &
              LDA(II) == LDA(J) .AND. LDB(II) == LDB(J) .AND. LDC(II) == LDC(J))
    ENDIF
    IF (SAME) THEN
      GROUP_SIZE(GROUP_COUNT) = GROUP_SIZE(GROUP_COUNT) + 1
    ELSE
      GROUP_COUNT = GROUP_COUNT + 1
      MC(GROUP_COUNT) = M(II)
      NC(GROUP_COUNT) = N(II)
      KC(GROUP_COUNT) = K(II)
      LDAC(GROUP_COUNT) = LDA(II)
      LDBC(GROUP_COUNT) = LDB(II)
      LDCC(GROUP_COUNT) = LDC(II)
      TRANSA_C(GROUP_COUNT) = TRA
      TRANSB_C(GROUP_COUNT) = TRB
      ALPHAC(GROUP_COUNT) = ALPHA
      BETAC(GROUP_COUNT) = BETA
      GROUP_SIZE(GROUP_COUNT) = 1
    ENDIF
  ENDDO

  CALL CBLAS_SGEMM_BATCH(CBLAS_COLMAJOR, TRANSA_C, TRANSB_C, &
      MC, NC, KC, ALPHAC, A_PERM, LDAC, B_PERM, LDBC, BETAC, C_PERM, LDCC, &
      GROUP_COUNT, GROUP_SIZE)
#else
  INTEGER(KIND=JPIM) :: I
